"""Build the task dataset: a class-balanced sample of tweets from dair-ai/emotion.

Downloads the test split (Parquet) from the Hugging Face Hub, filters out
sensitive or hard-to-read texts, takes PER_LABEL tweets per emotion in a
deterministic order, and writes:

  data/tweets.json     - the sampled tweets (for reference / analysis)
  supabase/seed.sql    - INSERT statements to load them into Supabase

Usage:
  python3 -m venv .venv && .venv/bin/pip install -r data/requirements.txt
  .venv/bin/python data/prepare_dataset.py
"""

import hashlib
import json
import random
import re
import urllib.request
from pathlib import Path

import pyarrow.parquet as pq

DATASET = "dair-ai/emotion"
SPLIT = "test"
PER_LABEL = 10
SEED = 2026
MIN_WORDS, MAX_WORDS = 6, 35

# Label order from the dataset card: 0 sadness, 1 joy, 2 love, 3 anger, 4 fear, 5 surprise
LABELS = ["sadness", "joy", "love", "anger", "fear", "surprise"]

# Texts touching on these topics are excluded so participants aren't shown distressing content.
BLOCKLIST = re.compile(
    r"\b(suicid\w*|kill\w*|die|died|dying|death|dead|rape\w*|abus\w*|self harm|cut myself|"
    r"sex\w*|horny|porn\w*|naked|nude|cock|fondl\w*|orgasm\w*|aroused|fuck\w*|shit\w*|bitch\w*|damn\w*|ass|dick\w*|"
    r"slut\w*|whore\w*|nigg\w*|fag\w*|retard\w*|drunk|drugs?|weed|cocaine|xanax|pills?|"
    r"href|http\w*|www)\b"
)

# Rows reviewed by hand and dropped: truncated or garbled text, page markup, drugs, politics.
EXCLUDE_ROWS = {14, 162, 338, 795, 1485, 1916}

ROOT = Path(__file__).resolve().parent.parent
PARQUET_URL = (
    f"https://huggingface.co/datasets/{DATASET}/resolve/main/split/{SPLIT}-00000-of-00001.parquet"
)
RAW_CACHE = ROOT / "data" / f"raw_{SPLIT}.parquet"


def fetch_split() -> list[dict]:
    """Download the split's Parquet file once and cache it, so re-running is offline."""
    if not RAW_CACHE.exists():
        urllib.request.urlretrieve(PARQUET_URL, RAW_CACHE)
    table = pq.read_table(RAW_CACHE).to_pylist()
    return [{"row_idx": i, **row} for i, row in enumerate(table)]


def keep(row: dict) -> bool:
    text = row["text"]
    return (
        row["row_idx"] not in EXCLUDE_ROWS
        and MIN_WORDS <= len(text.split()) <= MAX_WORDS
        and not BLOCKLIST.search(text)
    )


def stable_key(row: dict) -> str:
    # Deterministic per-row ordering: excluding one row swaps in exactly one replacement
    # instead of reshuffling the whole sample.
    return hashlib.sha256(f"{SEED}-{row['row_idx']}".encode()).hexdigest()


def sql_str(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def main() -> None:
    rows = [r for r in fetch_split() if keep(r)]
    rng = random.Random(SEED)

    sample = []
    for label_id, name in enumerate(LABELS):
        pool = sorted((r for r in rows if r["label"] == label_id), key=stable_key)
        for r in pool[:PER_LABEL]:
            sample.append(
                {"source_row": r["row_idx"], "text": r["text"], "ground_truth": name}
            )
    rng.shuffle(sample)
    for i, t in enumerate(sample, start=1):
        t["id"] = i

    (ROOT / "data" / "tweets.json").write_text(json.dumps(sample, indent=2) + "\n")

    values = ",\n".join(
        f"  ({t['id']}, {t['source_row']}, {sql_str(t['text'])}, {sql_str(t['ground_truth'])})"
        for t in sample
    )
    (ROOT / "supabase" / "seed.sql").write_text(
        f"-- Generated by data/prepare_dataset.py from {DATASET} ({SPLIT} split), "
        f"{PER_LABEL} tweets per label, seed {SEED}.\n"
        "insert into tweets (id, source_row, text, ground_truth) values\n"
        f"{values};\n"
    )

    counts = {n: sum(t["ground_truth"] == n for t in sample) for n in LABELS}
    print(f"{len(sample)} tweets written ({len(rows)} passed filters). Per label: {counts}")


if __name__ == "__main__":
    main()
